def test_http_errors_never_echo_remote_details(monkeypatch):
    s=service(); client=s.ArkPortraitClient(config()); captured={}
    class Response:
        status_code=200
        def json(self): return {'ResponseMetadata':{'Error':{'Message':'test-secret-key https://private/?token=foo'}}}
        def close(self): pass
    def post(url,**kwargs): captured.update(url=url,**kwargs); return Response()
    monkeypatch.setattr(s.requests,'post',post)
    with pytest.raises(s.PortraitError) as exc: client.get_asset('asset-example')
    assert 'test-secret-key' not in str(exc.value) and 'token' not in str(exc.value)
    assert captured['url']=='https://ark.cn-beijing.volcengineapi.com/?Action=GetAsset&Version=2024-01-01'
    assert captured['allow_redirects'] is False


