def test_get_asset_validates_group_and_project(monkeypatch):
    s=service(); client=s.ArkPortraitClient(config()); calls=[]
    def request(action,payload):
        calls.append((action,payload)); return asset() if action=='GetAsset' else group()
    monkeypatch.setattr(client,'_request',request)
    value=client.get_asset('asset-example')
    assert value['remote_asset_id']=='asset-example' and value['project']=='default'
    assert calls==[('GetAsset',{'Id':'asset-example','ProjectName':'default'}),('GetAssetGroup',{'Id':'group-example','ProjectName':'default'})]


