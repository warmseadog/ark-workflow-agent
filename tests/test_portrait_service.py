def test_signing_serialized_utf8_body_matches_sent_content(monkeypatch):
    import hashlib
    s=service(); client=s.ArkPortraitClient(config())
    class Response:
        status_code=200
        def json(self): return {'Result':{'Items':[]}}
        def close(self): pass
    def post(url,**kwargs):
        assert kwargs['headers']['X-Content-Sha256']==hashlib.sha256(kwargs['data']).hexdigest()
        assert json.loads(kwargs['data'])['ProjectName']=='中文项目'
        return Response()
    monkeypatch.setattr(s.requests,'post',post)
    assert client._request('ListAssets',{'ProjectName':'中文项目'})=={'Items':[]}
