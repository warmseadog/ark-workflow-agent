def asset(**changes):
    item = {'Id':'asset-example','Name':'肖像','GroupId':'group-example','ProjectName':'default','Status':'Active','AssetType':'Image','URL':'https://ark-asset.cn-beijing.volcengine.com/face.png?secret=hidden'}
